export const TRANSLATIONS = UI_TRANSLATIONS;

const KNOWN_LANGUAGES: Set<string> = new Set(["en", "es", "fr", "de", "ja", "pt", "zh"]);

/**
 * Get translated string with parameter interpolation and fallback to English.
 * Supports both `t(lang, key, params)` and `t(key, lang, params)`.
 */
export function t(
  first: string,
  second?: string | Record<string, unknown>,
  third?: Record<string, unknown>
): string {
  let lang: LanguageCode = "en";
  let key = "";
  let params: Record<string, unknown> | undefined;

  if (KNOWN_LANGUAGES.has(first) && typeof second === "string") {
    lang = first as LanguageCode;
    key = second;
    params = third;
  } else if (typeof first === "string" && typeof second === "string" && KNOWN_LANGUAGES.has(second)) {
    key = first;
    lang = second as LanguageCode;
    params = third;
  } else if (typeof first === "string") {
    key = first;
    if (second && typeof second === "object") {
      params = second;
    }
  }

  const dict = UI_TRANSLATIONS[lang] ?? UI_TRANSLATIONS.en;
  let text = dict[key] ?? UI_TRANSLATIONS.en[key] ?? key;

  if (params && typeof params === "object") {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(pVal));
    }
  }

  return text;
}

/**
 * Get translated label for a finding category.
 * Supports both `getCategoryLabel(lang, category)` and `getCategoryLabel(category, lang)`.
 */
export function getCategoryLabel(first: string, second?: string): string {
  let lang: LanguageCode = "en";
  let cat = first;

  if (KNOWN_LANGUAGES.has(first) && second) {
    lang = first as LanguageCode;
    cat = second;
  } else if (second && KNOWN_LANGUAGES.has(second)) {
    lang = second as LanguageCode;
    cat = first;
  }

  const catDict = CATEGORY_TRANSLATIONS[lang] ?? CATEGORY_TRANSLATIONS.en;
  return catDict[cat] ?? CATEGORY_TRANSLATIONS.en[cat] ?? cat;
}

/**
 * Get translated label for a compliance preset.
 * Supports both `getPresetLabel(lang, presetId)` and `getPresetLabel(presetId, lang)`.
 */
export function getPresetLabel(first: string, second?: string): string {
  let lang: LanguageCode = "en";
  let preset = first;

  if (KNOWN_LANGUAGES.has(first) && second) {
    lang = first as LanguageCode;
    preset = second;
  } else if (second && KNOWN_LANGUAGES.has(second)) {
    lang = second as LanguageCode;
    preset = first;
  }

  const presetDict = PRESET_TRANSLATIONS[lang] ?? PRESET_TRANSLATIONS.en;
  return presetDict[preset] ?? PRESET_TRANSLATIONS.en[preset] ?? preset;
}

/** Apply translations to DOM elements with data-i18n attributes. */
export function applyI18nToDom(root: ParentNode = document, lang: LanguageCode = "en"): void {
  const textElements = root.querySelectorAll<HTMLElement>("[data-i18n]");
  textElements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      const translated = t(lang, key);
      if (translated) el.textContent = translated;
    }
  });

  const placeholderElements = root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]");
  placeholderElements.forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      const translated = t(lang, key);
      if (translated) el.placeholder = translated;
    }
  });

  const titleElements = root.querySelectorAll<HTMLElement>("[data-i18n-title]");
  titleElements.forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      const translated = t(lang, key);
      if (translated) el.title = translated;
    }
  });

  const ariaElements = root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]");
  ariaElements.forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    if (key) {
      const translated = t(lang, key);
      if (translated) el.setAttribute("aria-label", translated);
    }
  });
}
